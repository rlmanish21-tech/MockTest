create extension if not exists pgcrypto;
create table if not exists public.profiles (
 id uuid primary key references auth.users(id) on delete cascade,
 full_name text not null,
 mobile text unique not null,
 date_of_birth date not null,
 stream text not null check(stream in ('Commerce','Science','Arts')),
 course_name text not null,
 state text not null,
 city text not null,
 qualification text not null,
 marketing_consent boolean not null default false,
 role text not null default 'student' check(role in ('student','admin')),
 created_at timestamptz not null default now()
);
create table if not exists public.courses (
 id bigint generated by default as identity primary key,
 name text not null,
 stream text not null check(stream in ('Commerce','Science','Arts')),
 is_active boolean not null default true,
 created_at timestamptz not null default now(),
 unique(name,stream)
);
create table if not exists public.tests (
 id bigint generated by default as identity primary key,
 title text not null,
 course_id bigint references public.courses(id),
 test_type text not null check(test_type in ('practice','live')),
 status text not null default 'draft' check(status in ('draft','published','closed')),
 duration_minutes integer not null default 90 check(duration_minutes between 1 and 300),
 question_count integer not null default 100 check(question_count > 0),
 starts_at timestamptz,
 ends_at timestamptz,
 created_by uuid references auth.users(id),
 created_at timestamptz not null default now()
);
create table if not exists public.questions (
 id bigint generated by default as identity primary key,
 test_id bigint not null references public.tests(id) on delete cascade,
 question_text text not null,
 option_a text not null, option_b text not null, option_c text not null, option_d text not null,
 marks numeric(8,2) not null default 1,
 negative_marks numeric(8,2) not null default 0,
 question_order integer not null,
 created_at timestamptz not null default now(),
 unique(test_id,question_order)
);
create table if not exists public.answer_keys (
 question_id bigint primary key references public.questions(id) on delete cascade,
 correct_option text not null check(correct_option in ('A','B','C','D'))
);
create table if not exists public.attempts (
 id bigint generated by default as identity primary key,
 test_id bigint not null references public.tests(id),
 student_id uuid not null references public.profiles(id),
 started_at timestamptz not null default now(),
 submitted_at timestamptz,
 status text not null default 'in_progress' check(status in ('in_progress','submitted','evaluated')),
 score numeric(10,2),
 max_score numeric(10,2),
 unique(test_id,student_id)
);
create table if not exists public.attempt_answers (
 id bigint generated by default as identity primary key,
 attempt_id bigint not null references public.attempts(id) on delete cascade,
 question_id bigint not null references public.questions(id) on delete cascade,
 selected_option text check(selected_option in ('A','B','C','D')),
 saved_at timestamptz not null default now(),
 unique(attempt_id,question_id)
);
create table if not exists public.results (
 id bigint generated by default as identity primary key,
 test_id bigint not null references public.tests(id),
 student_id uuid not null references public.profiles(id),
 score numeric(10,2) not null default 0,
 max_score numeric(10,2) not null default 0,
 rank integer,
 published_at timestamptz,
 created_at timestamptz not null default now(),
 unique(test_id,student_id)
);
create or replace function public.is_admin() returns boolean language sql stable security definer set search_path=public as $$
 select exists(select 1 from public.profiles where id=auth.uid() and role='admin')
$$;
